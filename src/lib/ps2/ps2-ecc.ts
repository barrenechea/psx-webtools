export const ECC_CHUNK_SIZE = 128;
export const ECC_CODE_SIZE = 3;
export const ECC_PAGE_DATA_SIZE = 512;
export const ECC_PAGE_SPARE_SIZE = 16;
export const ECC_PAGE_SIZE = ECC_PAGE_DATA_SIZE + ECC_PAGE_SPARE_SIZE;

// The code of an all-0xFF chunk; a written all-FF data page therefore carries
// 77 7F 7F four times (the trailing four spare bytes stay 0x00).
export const ECC_ALL_FF_CODE: readonly number[] = [0x77, 0x7f, 0x7f];

/** 3-byte Hamming code for one 128-byte chunk. */
export function calcEcc(data: Uint8Array, offset = 0): Uint8Array {
  if (data.length - offset < ECC_CHUNK_SIZE) {
    throw new Error("calcEcc needs a 128-byte chunk");
  }
  let e0 = 0;
  let e1 = 0;
  let e2 = 0;
  for (let i = 0; i < 0x80; i++) {
    const c = ECC_TABLE[data[offset + i]];
    e0 ^= c;
    if (c & 0x80) {
      e1 ^= ~i & 0xff;
      e2 ^= i;
    }
  }
  return new Uint8Array([
    (e0 ^ 0xff) & 0x77,
    (e1 ^ 0xff) & 0x7f,
    (e2 ^ 0xff) & 0x7f,
  ]);
}

/**
 * 16-byte spare area for a 512-byte data area: four 3-byte codes in chunk
 * order (spare[3c..3c+2]), trailing 4 bytes zero.
 */
export function pageSpare(data: Uint8Array): Uint8Array {
  if (data.length < ECC_PAGE_DATA_SIZE) {
    throw new Error("pageSpare needs 512 data bytes");
  }
  const out = new Uint8Array(ECC_PAGE_SPARE_SIZE);
  for (let c = 0; c < 4; c++) {
    const code = calcEcc(data, c * ECC_CHUNK_SIZE);
    out.set(code, c * ECC_CODE_SIZE);
  }
  return out;
}

export type PageEccStatus = "valid" | "erased" | "corrupt";

// A never-written page holds all-0xFF data AND all-0xFF spare (flash erase
// state); that is not corruption.
function isErased(data: Uint8Array, spare: Uint8Array): boolean {
  for (let i = 0; i < data.length; i++) {
    if (data[i] !== 0xff) return false;
  }
  for (let i = 0; i < spare.length; i++) {
    if (spare[i] !== 0xff) return false;
  }
  return true;
}

/** Validate one 528-byte page (512 data + 16 spare) against its stored ECC. */
export function checkPage(page: Uint8Array): PageEccStatus {
  if (page.length < ECC_PAGE_SIZE) {
    throw new Error("checkPage needs a 528-byte page");
  }
  const data = page.subarray(0, ECC_PAGE_DATA_SIZE);
  const spare = page.subarray(ECC_PAGE_DATA_SIZE, ECC_PAGE_SIZE);
  if (isErased(data, spare)) return "erased";
  for (let c = 0; c < 4; c++) {
    const code = calcEcc(data, c * ECC_CHUNK_SIZE);
    if (
      spare[c * 3] !== code[0] ||
      spare[c * 3 + 1] !== code[1] ||
      spare[c * 3 + 2] !== code[2]
    ) {
      return "corrupt";
    }
  }
  return "valid";
}
